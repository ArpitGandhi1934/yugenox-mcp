#!/usr/bin/env node
// Regenerates install-links.json from scripts/servers.mjs.
// Usage: node scripts/make-install-links.mjs
// Every link here is token-free: mcp.apify.com runs OAuth, so each user signs in to their
// own Apify account and pays for their own runs.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SERVERS, mcpUrl, actorToolName } from './servers.mjs';

const out = {
  note: 'Generated by scripts/make-install-links.mjs. No token in any link: mcp.apify.com runs OAuth, so every user signs in to their own Apify account and pays for their own runs.',
};

for (const s of SERVERS) {
  const url = mcpUrl(s);
  const httpConfig = { type: 'http', url };
  const cursorConfig = Buffer.from(JSON.stringify({ url })).toString('base64');
  const vscodeConfig = encodeURIComponent(JSON.stringify(httpConfig));
  out[s.key] = {
    name: s.name,
    mcpUrl: url,
    tools: ['fetch-actor-details', ...s.actors.map(actorToolName)],
    store: s.store,
    registryName: s.registryName,
    claudeCode: `claude mcp add --transport http ${s.name} "${url}"`,
    cursorDeeplink: `cursor://anysphere.cursor-deeplink/mcp/install?name=${s.name}&config=${cursorConfig}`,
    cursorWebLink: `https://cursor.com/en/install-mcp?name=${s.name}&config=${encodeURIComponent(cursorConfig)}`,
    vscodeDeeplink: `vscode:mcp/install?${encodeURIComponent(JSON.stringify({ name: s.name, ...httpConfig }))}`,
    vscodeWebLink: `https://insiders.vscode.dev/redirect/mcp/install?name=${s.name}&config=${vscodeConfig}`,
    vscodeInsidersWebLink: `https://insiders.vscode.dev/redirect/mcp/install?name=${s.name}&config=${vscodeConfig}&quality=insiders`,
    jsonConfig: { mcpServers: { [s.name]: httpConfig } },
    windsurfConfig: { mcpServers: { [s.name]: { serverUrl: url } } },
    stdioBridgeConfig: { mcpServers: { [s.name]: { command: 'npx', args: ['-y', 'mcp-remote', url] } } },
  };
}

const target = fileURLToPath(new URL('../install-links.json', import.meta.url));
writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${target}`);
